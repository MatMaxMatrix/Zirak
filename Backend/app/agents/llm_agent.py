    async def connect_to_mcp_server(self) -> bool:
        """
        Connect directly to the MCP server via SSE and initialize the session.

        Returns:
            bool: True if connected successfully or already connected, False otherwise
        """
        if self._mcp_connected and self.mcp_session:
            logger.info("Already connected to MCP server.")
            return True

        try:
            logger.info(
                f"Connecting directly to MCP server at {self.mcp_server_url}..."
            )
            self.console.print(
                f"[cyan]Connecting directly to MCP server at {self.mcp_server_url}...[/cyan]"
            )

            # Clean up previous stack if reconnecting
            if self.mcp_exit_stack:
                await self.mcp_exit_stack.aclose()
                self.mcp_exit_stack = AsyncExitStack()

            # Establish SSE connection and ClientSession
            streams = await self.mcp_exit_stack.enter_async_context(
                sse_client(self.mcp_server_url)
            )
            self.mcp_session = await self.mcp_exit_stack.enter_async_context(
                ClientSession(streams[0], streams[1])
            )
            await self.mcp_session.initialize()
            logger.info("MCP Session initialized successfully.")

            # Fetch available tools
            await self._fetch_and_process_mcp_tools()

            self._mcp_connected = True
            self.console.print(
                f"[green]Connected directly to MCP server. Found {len(self.available_mcp_tools)} tools.[/green]"
            )
            logger.info(
                f"Connected to MCP. Available tools: {', '.join(self.get_available_tool_names())}"
            )

            return True
        except Exception as e:
            error_msg = f"Failed to connect directly to MCP server: {str(e)}"
            self.console.print(
                f"[bold red]{error_msg}\n{traceback.format_exc()}[/bold red]"
            )
            logger.error(f"{error_msg}\n{traceback.format_exc()}")
            self._mcp_connected = False
            self.mcp_session = None  # Ensure session is None on failure
            await self.mcp_exit_stack.aclose()  # Clean up stack on failure
            self.mcp_exit_stack = AsyncExitStack()  # Re-initialize stack
            return False

    async def _fetch_and_process_mcp_tools(self):
        """Fetches and processes the list of available tools directly from the MCP session."""
        if not self.mcp_session:
            logger.error("Cannot fetch tools, MCP session not available.")
            self.available_mcp_tools = []
            return

        try:
            logger.info("Fetching available tools directly from MCP session...")
            # Assuming list_tools() returns a result object with a 'tools' attribute or similar
            # Adjust the extraction logic based on the actual return type of
            # self.mcp_session.list_tools()
            tools_result = await self.mcp_session.list_tools()

            # Helper to extract tools from potentially varied result structures
            mcp_tools_raw = self._extract_mcp_data(tools_result, "tools")

            if not isinstance(mcp_tools_raw, list):
                logger.warning(
                    f"Received non-list tools data from MCP: {type(mcp_tools_raw)}"
                )
                mcp_tools_raw = []

            logger.info(f"Found {len(mcp_tools_raw)} raw tools from MCP.")

            # Process each tool into a standardized dictionary format
            processed_tools = []
            for tool_raw in mcp_tools_raw:
                try:
                    processed_tools.append(self._process_mcp_tool_definition(tool_raw))
                except Exception as e:
                    logger.error(
                        f"Error processing raw tool definition: {tool_raw} - Error: {e}"
                    )

            self.available_mcp_tools = processed_tools
            logger.info(f"Processed {len(self.available_mcp_tools)} tools.")

        except Exception as e:
            logger.error(
                f"Failed to fetch or process tools from MCP: {e}\n{traceback.format_exc()}"
            )
            self.available_mcp_tools = []

    def _extract_mcp_data(self, result_obj: Any, expected_attr: str) -> Any:
        """Extracts data from various MCP result object formats."""
        if hasattr(result_obj, expected_attr):
            return getattr(result_obj, expected_attr)
        # Add more checks here if MCP returns results in other formats (e.g.,
        # dict)
        if isinstance(result_obj, dict) and expected_attr in result_obj:
            return result_obj[expected_attr]
        if isinstance(result_obj, list):
            # If the result itself is a list, maybe that's what we want?
            # This depends heavily on the MCP API contract. Assuming list_tools
            # returns an obj with .tools for now.
            logger.warning(
                f"MCP result was a list, expected object with attribute '{expected_attr}'. Returning list."
            )
            return result_obj
        logger.warning(
            f"Could not extract '{expected_attr}' from MCP result type: {type(result_obj)}"
        )
        return None  # Indicate data wasn't found as expected

    def _process_mcp_tool_definition(self, tool_data: Any) -> Dict[str, Any]:
        """Converts a raw tool definition from MCP into a standardized dictionary."""
        processed = {
            "name": "UnknownTool",
            "description": "No description available.",
            "inputSchema": {},
            "annotations": {},
        }

        if isinstance(tool_data, dict):
            processed["name"] = tool_data.get("name", processed["name"])
            processed["description"] = tool_data.get(
                "description", processed["description"]
            )
            processed["inputSchema"] = tool_data.get(
                "inputSchema", tool_data.get("schema", processed["inputSchema"])
            )
            processed["annotations"] = tool_data.get(
                "annotations", processed["annotations"]
            )
        elif hasattr(tool_data, "name"):  # Check for object attributes
            processed["name"] = getattr(tool_data, "name", processed["name"])
            processed["description"] = getattr(
                tool_data, "description", processed["description"]
            )
            # Handle schema attribute possibilities
            if hasattr(tool_data, "inputSchema"):
                processed["inputSchema"] = getattr(
                    tool_data, "inputSchema", processed["inputSchema"]
                )
            elif hasattr(tool_data, "schema"):
                processed["inputSchema"] = getattr(
                    tool_data, "schema", processed["inputSchema"]
                )
            processed["annotations"] = getattr(
                tool_data, "annotations", processed["annotations"]
            )
        else:
            logger.warning(f"Unrecognized raw tool data format: {type(tool_data)}")

        # Ensure inputSchema is a dict
        if not isinstance(processed["inputSchema"], dict):
            logger.warning(
                f"Tool '{processed['name']}' has non-dict inputSchema: {type(processed['inputSchema'])}. Resetting to empty dict."
            )
            processed["inputSchema"] = {}

        return processed

