    async def chat(self, user_input):
        """
        Process a message from the user and generate a response.

        This method:
        1. Handles special commands (refresh, reset, info, quit)
        2. Adds the user message to conversation history
        3. Gets a completion from the model
        4. Ensures directories and files are properly explored

        Args:
            user_input: The user's message (string or multimodal content)

        Returns:
            str: The response to the user
        """
        # Handle special commands
        if isinstance(user_input, str):
            if user_input.lower() == "refresh":
                success = await self.refresh_tools()
                if success:
                    self.display_available_tools()
                    return "Tools refreshed successfully from MCP server."
                else:
                    return "Failed to refresh tools. Check MCP server connection."

            elif user_input.lower() == "reset":
                await self.reset()
                return "Conversation reset! Ready for new requests."

            elif user_input.lower() == "quit":
                return "Goodbye! Session ended."

            elif user_input.lower() == "info":
                return self._display_conversation_info()

            elif (
                user_input.lower() == "tools"
                or user_input.lower() == "display_available_tools"
            ):
                self.display_available_tools()
                return f"Displayed {len(self.tools)} available tools from MCP server."

        try:
            # Connect to MCP if not already connected
            await self.connect_to_mcp_server()

            # Add the user message to conversation history
            self.conversation_history.append({"role": "user", "content": user_input})

            # Reset the tool call counter for this new interaction
            self.current_auto_tool_calls = 0

            # Display thinking indicator if enabled
            if self.thinking_enabled:
                self.console.print("[cyan]Thinking...[/cyan]")

            # Store the user input for reference in recursive completions
            self.user_input = user_input

            # Get the completion
            response = await self._get_completion()

            # After getting a response, verify context and directories
            await self._ensure_directories_explored()
            await self._check_mentioned_files()

            return response

        except Exception as e:
            import traceback

            error_msg = f"Error in chat: {str(e)}"
            logger.error(f"{error_msg}\n{traceback.format_exc()}")

            if "closing tag" in str(e) and "doesn't match any open tag" in str(e):
                return "Error: There's an issue with the formatting of the response. Please check the template tags."

            error_msg = error_msg.replace("[", r"\\[").replace("]", r"\\]")
            return error_msg

    async def main(self, *args, **kwargs):
        """
        Main entry point for the agent when used with AutoGen.

        Args:
            *args: Variable length argument list
            **kwargs: Arbitrary keyword arguments

        Returns:
            tuple: (final, reply) where final is a boolean indicating if the conversation should end,
                  and reply is the response message
        """
        try:
            # Ensure connection to MCP server
            success = await self.connect_to_mcp_server()
            if not success:
                return True, {
                    "role": "assistant",
                    "content": "Failed to connect to MCP server. Please check connection and try again.",
                }

            # Reset conversation state
            await self.reset()

            final_response_content = "No specific outcome determined."

            # Process messages from AutoGen
            if args or kwargs:
                messages = kwargs.get("messages", [])
                if messages:
                    last_message = messages[-1]
                    sender_name = last_message.get("name", "")
                    content = last_message.get("content", "")

                    if sender_name == "UserProxyAgent":
                        self.console.print(
                            f"[cyan]Received request from UserProxyAgent: {content}[/cyan]"
                        )
                        response = await self.chat(content)
                        # The 'response' from chat is the direct result of that interaction.
                        # The overall summary will be generated after this block.
                        final_response_content = response

                    self.console.print(
                        f"[cyan]Processing message from {sender_name}: {content}[/cyan]"
                    )

                    # Handle step-based execution
                    if hasattr(self, "context") and "steps" in self.context:
                        step_keys = sorted(
                            [
                                k
                                for k in self.context["steps"].keys()
                                if k.startswith("step")
                            ]
                        )

                        step_response = "No specific step response."
                        while self.current_step_index < len(step_keys):
                            current_step_key = step_keys[self.current_step_index]
                            current_step = self.context["steps"][current_step_key]

                            if (
                                isinstance(current_step, dict)
                                and "description" in current_step
                            ):
                                step_description = current_step["description"]
                                step_details = current_step.get("details", "")

                                self.console.print(
                                    f"[bold cyan]Processing step {self.current_step_index + 1}/{len(step_keys)}: {step_description}[/bold cyan]"
                                )
                                self.current_step_index += 1

                                step_response = await self.chat(
                                    f"Execute step: {step_description}\n\nDetails: {step_details}"
                                )
                            else:
                                self.console.print(
                                    f"[bold cyan]Processing step {self.current_step_index + 1}/{len(step_keys)}[/bold cyan]"
                                )
                                self.current_step_index += 1

                                step_response = await self.chat(
                                    f"Execute step: {current_step}"
                                )

                        self.console.print(
                            "[bold yellow]All steps completed.[/bold yellow]"
                        )
                        final_response_content = (
                            step_response  # The result of the last step
                        )
                        # The summary will be generated after this block.

                    # If not UserProxyAgent and not step-based, it might be another agent.
                    # For now, the last response from chat will be the basis if no other logic
                    # overrides.
                    elif not sender_name == "UserProxyAgent":
                        final_response_content = await self.chat(content)

            # Try to extract user input from various sources if not already handled by
            # UserProxyAgent or steps
            if (
                final_response_content == "No specific outcome determined."
            ):  # Indicates UserProxyAgent/steps didn't set it
                user_input = ""
                # From context
                if hasattr(self, "context"):
                    user_input = self.context.get("user_input", "")

                # From messages
                if not user_input and (args or kwargs):
                    messages = kwargs.get("messages", [])
                    if messages:
                        user_input = messages[-1].get("content", "")

                # If no user input found, this path might not be hit if UserProxyAgent or steps always provide input.
                # If it IS hit, it means the agent was invoked by AutoGen without a clear
                # initial task in the typical flow.
                if not user_input:
                    self.console.print(
                        "[yellow]LLM_Agent.main was called without a clear user_input from known sources. Returning pending state.[/yellow]"
                    )
                    return False, {
                        "role": "assistant",
                        "content": "LLM Agent with MCP initialized and awaiting further input or termination.",
                    }

                # Handle special commands if user_input was found this way
            if user_input.lower() == "quit":
                self.console.print(
                    "\n[bold blue]👋 Goodbye! (quit command via main loop)[/bold blue]"
                )
                final_response_content = "Execution quit by command."
                # Summary will still be generated for actions before quit
            elif user_input.lower() == "reset":
                await self.reset()
                # This effectively restarts the main logic for the current AutoGen message
                return await self.main(*args, **kwargs)
            else:
                # Process this directly found user_input
                self.console.print(
                    f"[cyan]Processing direct user_input in main: {user_input}[/cyan]"
                )
                final_response_content = await self.chat(user_input)

            # Generate and return the final summary of all actions performed in this main() call
            final_summary = self._generate_final_summary()

            # Log the original intended response before overriding with summary, if it
            # was substantial
            if (
                final_response_content
                not in ["No specific outcome determined.", "Execution quit by command."]
                and final_response_content != final_summary
            ):
                logger.info(
                    f"Original final response content (before summary): {final_response_content}"
                )

            self.console.print(
                f"\n[bold magenta]Final Summary for Central Manager:[/bold magenta]\n{final_summary}"
            )
            return True, {"role": "assistant", "content": final_summary}

        except KeyboardInterrupt:
            self.console.print(
                "\n[bold yellow]Operation interrupted by user[/bold yellow]"
            )
            return True, {
                "role": "assistant",
                "content": "Operation interrupted by user",
            }

        except Exception as e:
            import traceback

            error_msg = f"Critical error in main: {str(e)}"
            self.console.print(f"[bold red]{error_msg}[/bold red]")
            logger.error(f"{error_msg}\n{traceback.format_exc()}")
            return True, {"role": "assistant", "content": f"Critical error: {str(e)}"}

    def _generate_final_summary(self) -> str:
        """
        Generate a summary of all steps performed during the current agent execution.
        This summary is compiled from the agent's report_memory.

        Returns:
            str: A formatted string summarizing the steps performed.
        """
        if not self.context_manager.report_memory:
            logger.info("No steps recorded in report_memory to summarize.")
            return "No specific actions were recorded to summarize for this task."

        summary_parts = ["Summary of actions performed:"]
        for idx, entry in enumerate(self.context_manager.report_memory):
            content = entry.get("content", "")

            # Try to extract a cleaner step summary from the typical format
            # "report summary for step X: {actual_report_content}"
            match = re.search(
                r"report summary for step\s*\d+:\s*(.*)",
                content,
                re.DOTALL | re.IGNORECASE,
            )
            if match:
                step_report = match.group(1).strip()
                # Prepend with a step number if not already clear from the report itself
                # However, the report_memory entries might not correspond 1:1 with original step numbers if there were retries or sub-steps.
                # Using enumerate index for clarity here.
                summary_parts.append(f"Action {idx + 1}: {step_report}")
            else:
                # Fallback if the content doesn't match the expected prefix
                summary_parts.append(f"Action {idx + 1}: {content}")

        final_summary = "\n".join(summary_parts)
        logger.info(f"Generated final summary: {final_summary}")
        return final_summary

    async def _ensure_directories_explored(self):
        """
        Ensure that all directories in the current context are explored for file content.
        This method checks if directories have been properly explored and contain files.
        If a directory appears to be empty or unexplored, it will trigger a list_directory
        tool call to explore it.
        """
        if not hasattr(self, "context_manager") or not hasattr(
            self.context_manager, "current_directories"
        ):
            return

        for directory in list(self.context_manager.current_directories):
            if not os.path.exists(directory):
                self.console.print(
                    f"[yellow]Directory {directory} does not exist. Removing from context.[/yellow]"
                )
                self.context_manager.current_directories.remove(directory)
                continue

            try:
                # Check if directory is empty
                contents = os.listdir(directory)
                if not contents:
                    self.console.print(
                        f"[yellow]Directory {directory} is empty.[/yellow]"
                    )
                    continue

                # Check if we have explored this directory (if any files from this
                # directory are in current_files)
                directory_explored = False
                for file in self.context_manager.current_files:
                    if file.startswith(directory):
                        directory_explored = True
                        break

                if not directory_explored:
                    self.console.print(
                        f"[yellow]Directory {directory} has not been explored. Exploring...[/yellow]"
                    )

                    # Create a mock tool use object for list_directory
                    class ToolUseMock:
                        def __init__(self, name, input_data):
                            self.name = name
                            self.input = input_data

                    tool_use = ToolUseMock(
                        "list_directory", {"directory_path": directory}
                    )
                    result = await self._execute_tool(tool_use)

                    # Add the tool call and result to conversation history
                    tool_call_id = f"auto_list_{directory}"
                    self.conversation_history.append(
                        {
                            "role": "assistant",
                            "content": None,
                            "tool_calls": [
                                {
                                    "id": tool_call_id,
                                    "type": "function",
                                    "function": {
                                        "name": "list_directory",
                                        "arguments": json.dumps(
                                            {"directory_path": directory}
                                        ),
                                    },
                                }
                            ],
                        }
                    )

                    self.conversation_history.append(
                        {
                            "role": "tool",
                            "tool_call_id": tool_call_id,
                            "name": "list_directory",
                            "content": str(
                                result
                            ),  # Ensure result is JSON serializable string
                        }
                    )

                    self.console.print(
                        f"[green]Directory {directory} explored.[/green]"
                    )

                    # Check if the directory needs deeper exploration
                    self._explore_directory_deeper(directory, contents)
            except Exception as e:
                self.console.print(
                    f"[red]Error exploring directory {directory}: {str(e)}[/red]"
                )

